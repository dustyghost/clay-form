//! UI intent; execution and file access belong to the application controller.
use crate::sculpt::{AdaptiveSettings, Brush, Kind, Symmetry};
#[derive(Clone)]
pub(crate) enum PendingAction {
    New,
    Open(String),
    Quit,
}
pub(crate) enum Command {
    Request(PendingAction),
    Save,
    Export,
    Undo,
    Redo,
    ClearMask,
    RequestPrimitive,
    ConfirmPrimitive,
    CancelPrimitive,
    UpdatePrimitive(crate::sculpt::Primitive),
    EndPrimitiveEdit,
    ConvertPrimitive,
    SelectSubmodel(usize),
    EditSubmodel(usize, String, crate::sculpt::ModelMetadata),
    ReorderSubmodel(usize, usize),
    AddGroup(String),
    RemoveGroup(String),
    ReorderGroup(usize, usize),
    GroupVisible(String, bool),
    TransformMode(crate::viewport::TransformMode),
    TransformOperation(crate::viewport::TransformOperation),
    RespectTransformMask(bool),
    DuplicateModel,
    ExtractMasked,
    ResetView,
    ZoomIn,
    ZoomOut,
    SetZoom(f32),
    Subdivide,
    SetMeshLevel(usize),
    DeleteLowerLevels,
    DeleteHigherLevels,
    SetDynamicMesh(bool),
    SetAdaptive(AdaptiveSettings),
    SetRemeshSettings(u32, bool),
    Remesh,
    CancelMeshJob,
    SetSymmetry(Symmetry),
    AddBrush(Kind),
    DuplicateBrush(usize),
    UpdateBrush(usize, Brush),
    LoadAlpha(usize),
    SavePreset(usize),
    LoadPreset,
    CaptureBrushIcon(usize),
    ExportIconImage(String, crate::sculpt::BrushIcon),
    ExportBrushLibrary,
    ImportBrushLibrary,
    SaveAndContinue,
    DiscardAndContinue,
    CancelPending,
}
